import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { FORM_REGISTRY } from '../src/config/form-registry';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function toPascalCase(str: string): string {
  return str.replace(/(^\w|-\w)/g, clear => clear.replace('-', '').toUpperCase());
}

interface RouteExtension {
  name: string;
  component: string;
  slot: string;
  order?: number;
  meta?: {
    slot: string;
    path: string;
    title: string;
  };
  online: boolean;
  offline: boolean;
}

interface RoutesConfig {
  $schema: string;
  _comment?: string;
  extensions: RouteExtension[];
}

export function generateRoutes(): RoutesConfig {
  const extensions: RouteExtension[] = [];

  for (const entry of FORM_REGISTRY) {
    const pascal = toPascalCase(entry.key);

    // Link extension
    extensions.push({
      name: `aiims-${entry.key}-dashboard-link`,
      component: `aiims${pascal}DashboardLink`,
      slot: 'patient-chart-dashboard-slot',
      order: entry.order,
      meta: {
        slot: entry.slot,
        path: entry.path,
        title: entry.title,
      },
      online: true,
      offline: true,
    });

    // Dashboard extension
    extensions.push({
      name: `aiims-${entry.key}-dashboard`,
      component: `aiims${pascal}Dashboard`,
      slot: entry.slot,
      online: true,
      offline: true,
    });

    // Demographics summary widget special case
    if (entry.key === 'demographics') {
      extensions.push({
        name: 'aiims-demographics-summary-widget',
        component: 'aiimsDemographicsSummaryWidget',
        slot: 'patient-info-slot',
        online: true,
        offline: true,
      });
    }
  }

  return {
    $schema: 'https://json.openmrs.org/routes.schema.json',
    _comment: 'AUTO-GENERATED by scripts/generate-routes.ts. Do not edit manually.',
    extensions,
  };
}

export function generateFormExtensionsTs(): string {
  const lines: string[] = [
    '// AUTO-GENERATED by scripts/generate-routes.ts. Do not edit manually.',
    "import React from 'react';",
    "import { getAsyncLifecycle, getSyncLifecycle } from '@openmrs/esm-framework';",
    "import { createDashboardLink } from './shared/components/dashboard-link.component';",
    "import { FORM_REGISTRY, moduleName } from './constants';",
    "import type { FormRegistryEntry } from './shared/types';",
    '',
    'type DashboardLoader = () => Promise<{ default: React.ComponentType<any> }>;',
    '',
    'export function createFormExtensions(',
    '  entry: FormRegistryEntry,',
    '  loadDashboard: DashboardLoader',
    ') {',
    '  const options = {',
    '    featureName: entry.key,',
    '    moduleName,',
    '    order: entry.order,',
    '  };',
    '',
    '  return {',
    '    link: getSyncLifecycle(',
    '      createDashboardLink({',
    '        path: entry.path,',
    '        title: entry.title,',
    '        titleKey: entry.titleKey,',
    '        icon: entry.icon,',
    '      }),',
    '      options',
    '    ),',
    '    dashboard: getAsyncLifecycle(loadDashboard, options),',
    '  };',
    '}',
    '',
    '// Manifest mapping each form key to its lazy dashboard component loader',
    'export const FORM_MODULES: Record<string, DashboardLoader> = {',
  ];

  for (const entry of FORM_REGISTRY) {
    const dir = entry.dir || entry.key;
    lines.push(`  '${entry.key}': () => import('./${dir}/${entry.key}-dashboard.component'),`);
  }
  lines.push('};');
  lines.push('');

  lines.push('// Generate Single-SPA extension lifecycles');
  lines.push('const _extensions: Record<string, any> = {};');
  lines.push('for (const entry of FORM_REGISTRY) {');
  lines.push('  const loader = FORM_MODULES[entry.key];');
  lines.push('  if (loader) {');
  lines.push('    const pascal = entry.key.replace(/(^\\w|-\\w)/g, clear => clear.replace(\'-\', \'\').toUpperCase());');
  lines.push('    const exts = createFormExtensions(entry, loader);');
  lines.push("    _extensions[`aiims${pascal}DashboardLink`] = exts.link;");
  lines.push("    _extensions[`aiims${pascal}Dashboard`] = exts.dashboard;");
  lines.push('  }');
  lines.push('}');
  lines.push('');

  lines.push('// Named exports required by Single-SPA at bundle time');
  lines.push('export const {');
  for (const entry of FORM_REGISTRY) {
    const pascal = toPascalCase(entry.key);
    lines.push(`  aiims${pascal}DashboardLink,`);
    lines.push(`  aiims${pascal}Dashboard,`);
  }
  lines.push('} = _extensions;');
  lines.push('');

  lines.push('// Feature module re-exports');
  for (const entry of FORM_REGISTRY) {
    const dir = entry.dir || entry.key;
    const indexPath = path.resolve(__dirname, `../src/${dir}/index.ts`);
    if (fs.existsSync(indexPath)) {
      lines.push(`export * from './${dir}';`);
    }
  }
  lines.push('');

  return lines.join('\n');
}

// 1. Generate src/routes.json
const routesOutputPath = path.resolve(__dirname, '../src/routes.json');
const routes = generateRoutes();
fs.writeFileSync(routesOutputPath, JSON.stringify(routes, null, 2) + '\n', 'utf-8');
console.log(`Successfully generated ${routes.extensions.length} extensions in src/routes.json`);

// 2. Generate src/generated-form-extensions.ts
const extensionsOutputPath = path.resolve(__dirname, '../src/generated-form-extensions.ts');
const extensionsTs = generateFormExtensionsTs();
fs.writeFileSync(extensionsOutputPath, extensionsTs, 'utf-8');
console.log(`Successfully generated extensions manifest and named exports in src/generated-form-extensions.ts`);
